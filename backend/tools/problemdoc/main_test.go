package main

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/guided-traffic/dash/backend/internal/problem"
)

func TestEnumListsEveryCodeInOrder(t *testing.T) {
	got := string(enumYAML([]problem.Code{problem.NotFound, problem.Internal}))
	assert.Equal(t, "# Generated by `make generate` from backend/internal/problem; do not edit.\n"+
		"ProblemCode:\n  type: string\n  description: The stable code of a problem\n  enum:\n    - not_found\n    - internal\n", got)
}

func TestTableEscapesAPipe(t *testing.T) {
	got := string(table([]problem.Code{{Code: "x", Status: 400, Meaning: "a | b"}}))
	assert.Equal(t, "| `code` | Status | Meaning |\n|---|---|---|\n| `x` | 400 | a \\| b |\n", got)
}

func TestReplaceBetweenKeepsWhatSurroundsTheMarkers(t *testing.T) {
	doc := []byte("before\n" + startMark + "\nold\n" + endMark + "\nafter\n")
	got, err := replaceBetween(doc, []byte("new\n"))
	require.NoError(t, err)
	assert.Equal(t, "before\n"+startMark+"\nnew\n"+endMark+"\nafter\n", string(got))
}

func TestReplaceBetweenNeedsBothMarkers(t *testing.T) {
	_, err := replaceBetween([]byte("no markers"), nil)
	assert.Error(t, err)
	_, err = replaceBetween([]byte(endMark+startMark), nil)
	assert.Error(t, err)
}

func TestRunWritesBothFiles(t *testing.T) {
	dir := t.TempDir()
	enum := filepath.Join(dir, "codes.yaml")
	readme := filepath.Join(dir, "README.md")
	require.NoError(t, os.WriteFile(readme, []byte(startMark+"\n"+endMark+"\n"), 0o600))

	require.NoError(t, run(enum, readme))

	gotEnum, err := os.ReadFile(enum)
	require.NoError(t, err)
	assert.Contains(t, string(gotEnum), "    - not_ready\n")
	gotReadme, err := os.ReadFile(readme)
	require.NoError(t, err)
	assert.Contains(t, string(gotReadme), "| `not_ready` | 503 |")
}

func TestRunFailsWithoutTheREADME(t *testing.T) {
	dir := t.TempDir()
	assert.Error(t, run(filepath.Join(dir, "codes.yaml"), filepath.Join(dir, "absent.md")))
}
