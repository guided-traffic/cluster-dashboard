// Command problemdoc writes what the problem catalogue decides: the OpenAPI
// enum of the codes, and the table of codes in the README between its
// markers. `make generate` runs it from backend/.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"strings"

	"github.com/guided-traffic/dash/backend/internal/problem"
)

const (
	enumFile   = "api/components/problem-codes.yaml"
	readmeFile = "../README.md"
	startMark  = "<!-- problem-codes:start -->"
	endMark    = "<!-- problem-codes:end -->"
)

func main() {
	if err := run(enumFile, readmeFile); err != nil {
		fmt.Fprintf(os.Stderr, "problemdoc: %v\n", err)
		os.Exit(1)
	}
}

func run(enumPath, readmePath string) error {
	if err := os.WriteFile(enumPath, enumYAML(problem.Catalogue), 0o600); err != nil {
		return fmt.Errorf("write %s: %w", enumPath, err)
	}
	readme, err := os.ReadFile(readmePath) // #nosec G304 -- the repository's README, a constant of main; the tests pass a file of their own
	if err != nil {
		return fmt.Errorf("read %s: %w", readmePath, err)
	}
	updated, err := replaceBetween(readme, table(problem.Catalogue))
	if err != nil {
		return err
	}
	if err := os.WriteFile(readmePath, updated, 0o600); err != nil {
		return fmt.Errorf("write %s: %w", readmePath, err)
	}
	return nil
}

func enumYAML(codes []problem.Code) []byte {
	var b bytes.Buffer
	b.WriteString("# Generated by `make generate` from backend/internal/problem; do not edit.\n")
	b.WriteString("ProblemCode:\n  type: string\n  description: The stable code of a problem\n  enum:\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "    - %s\n", c.Code)
	}
	return b.Bytes()
}

func table(codes []problem.Code) []byte {
	var b bytes.Buffer
	b.WriteString("| `code` | Status | Meaning |\n|---|---|---|\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "| `%s` | %d | %s |\n", c.Code, c.Status, strings.ReplaceAll(c.Meaning, "|", "\\|"))
	}
	return b.Bytes()
}

func replaceBetween(doc, content []byte) ([]byte, error) {
	start := bytes.Index(doc, []byte(startMark))
	end := bytes.Index(doc, []byte(endMark))
	if start < 0 || end < start {
		return nil, errors.New("the README lacks the problem-codes markers")
	}
	var out bytes.Buffer
	out.Write(doc[:start+len(startMark)])
	out.WriteString("\n")
	out.Write(content)
	out.Write(doc[end:])
	return out.Bytes(), nil
}
